/** 답(문항 id → -3~3)으로 축별 왼쪽 글자 비율(0~100)과 유형 */
export function scoreAnswers(answers: Record<number, number>) {
  const pct = {} as Record<Axis, number>
  for (const axis of AXES) {
    const left = AXIS_INFO[axis].left
    const qs = QUESTIONS.filter((q) => q.axis === axis)
    const sum = qs.reduce((a, q) => a + (answers[q.id] ?? 0) * (q.pole === left ? 1 : -1), 0)
    pct[axis] = Math.round(50 + (50 * sum) / (qs.length * 3))
  }
  const type = AXES.map((a) => (pct[a] > 50 ? AXIS_INFO[a].left : AXIS_INFO[a].right)).join('')
  return { pct, type }
}

